def render_html_from_markdown(markdown_text: str, title: str = "yunhee Document") -> str:
    """마크다운 문자열을 스타일이 적용된 완성형 HTML 문서로 변환."""
    html_body = markdown.markdown(
        markdown_text,
        extensions=["tables", "fenced_code"],
    )
    return HTML_TEMPLATE.format(title=title, body=html_body)


def convert_markdown_to_pdf(
    markdown_text: str,
    output_path: Path | str,
    title: str = "yunhee Document",
    gotenberg_url: str | None = None,
) -> tuple[bool, str]:
    """
    마크다운 문자열을 HTML로 감싸 Gotenberg Chromium 변환 API를 통해 PDF로 저장합니다.

    Returns:
        (성공여부, 안내문자열)
    """
    url = (gotenberg_url or config.GOTENBERG_URL).rstrip("/")
    target_api = f"{url}/forms/chromium/convert/html"
    out_file = Path(output_path).resolve()
    out_file.parent.mkdir(parents=True, exist_ok=True)

    html_content = render_html_from_markdown(markdown_text, title=title)
    files = {"files": ("index.html", html_content.encode("utf-8"), "text/html")}

    try:
        with httpx.Client(timeout=DEFAULT_GOTENBERG_TIMEOUT) as client:
            resp = client.post(target_api, files=files)
            if resp.status_code == 200 and resp.headers.get("content-type", "").startswith("application/pdf"):
                out_file.write_bytes(resp.content)
                size_kb = len(resp.content) / 1024
                return True, f"✔ PDF 발간 완료: {out_file} ({size_kb:.1f} KB)"
            return False, f"Gotenberg PDF 변환 실패 ({resp.status_code}): {resp.text}"
    except httpx.ConnectError:
        return False, f"Gotenberg 서버 연결 실패: {url} (서버가 기동 중인지 확인하세요)"
    except Exception as e:  # noqa: BLE001
        logger.warning("Gotenberg 변환 중 예외: %s", e)
        return False, f"Gotenberg 변환 중 오류 발생: {e}"


def export_pdf_from_file(
    markdown_file_path: Path | str,
    output_pdf_path: Path | str | None = None,
    gotenberg_url: str | None = None,
) -> tuple[bool, str]:
    """
    기존 마크다운 파일을 읽어 동일한 이름의 PDF(또는 지정 경로)로 변환 발간합니다.
    """
    src_file = Path(markdown_file_path).resolve()
    if not src_file.is_file():
        return False, f"error: 마크다운 파일이 존재하지 않습니다: {src_file}"

    try:
        content = src_file.read_text(encoding="utf-8")
    except Exception as e:  # noqa: BLE001
        return False, f"error: 파일 읽기 실패 ({src_file}): {e}"

    if output_pdf_path:
        dest_path = Path(output_pdf_path).resolve()
    else:
        # docs/pdf/ 아래에 동일한 stem으로 저장
        dest_path = Path(config.WORK_DIR) / "docs" / "pdf" / f"{src_file.stem}.pdf"

    title = src_file.stem.replace("_", " ").title()
    return convert_markdown_to_pdf(content, dest_path, title=title, gotenberg_url=gotenberg_url)
